#[test]
fn content_rules() {
    assert_eq!(content_skip_reason(b"fn main() {}\n"), None);
    assert_eq!(
        content_skip_reason(b"\x89PNG\r\n\x1a\n\0\0\0"),
        Some(SkipReason::Binary)
    );

    let minified = format!("var a={};\n", "x".repeat(3000));
    assert_eq!(
        content_skip_reason(minified.as_bytes()),
        Some(SkipReason::Minified)
    );
    let long_but_normal = "let value = compute();\n".repeat(200);
    assert_eq!(content_skip_reason(long_but_normal.as_bytes()), None);

    assert_eq!(
        content_skip_reason(b"// @generated by protoc\npackage x\n"),
        Some(SkipReason::Generated)
    );
    assert_eq!(
        content_skip_reason(b"// Code generated by mockgen. DO NOT EDIT.\npackage x\n"),
        Some(SkipReason::Generated)
    );
    // Markers outside the first ten lines, or split over two lines, do not count.
    let late_marker = format!("{}// @generated\n", "line\n".repeat(12));
    assert_eq!(content_skip_reason(late_marker.as_bytes()), None);
    assert_eq!(
        content_skip_reason(b"// Code generated here\n// DO NOT EDIT manually\n"),
        None
    );
}

#[test]
fn plan_diff_cases() {
    let existing: HashMap<String, String> = [
        ("a.rs".to_string(), "sha-a".to_string()),
        ("b.rs".to_string(), "sha-b".to_string()),
        ("gone.rs".to_string(), "sha-g".to_string()),
    ]
    .into_iter()
    .collect();
    let tree = vec![
        entry("a.rs", "sha-a"),
        entry("b.rs", "sha-b2"),
        entry("new.rs", "sha-n"),
    ];

    let plan = plan_diff(&existing, &tree, false);
    let fetched: Vec<&str> = plan.fetch.iter().map(|e| e.path.as_str()).collect();
    assert_eq!(fetched, ["b.rs", "new.rs"]);
    assert_eq!(plan.delete, ["gone.rs"]);

    let unchanged = plan_diff(
        &existing,
        &[
            entry("a.rs", "sha-a"),
            entry("b.rs", "sha-b"),
            entry("gone.rs", "sha-g"),
        ],
        false,
    );
    assert!(unchanged.fetch.is_empty());
    assert!(unchanged.delete.is_empty());

    let forced = plan_diff(&existing, &tree, true);
    assert_eq!(forced.fetch.len(), 3);
    assert_eq!(forced.delete, ["gone.rs"]);
}

#[test]
fn prepare_file_classifies_and_normalises() {
    let binary = prepare_file("img.png", "sha", b"\x89PNG\0\0");
    assert!(matches!(
        binary.outcome,
        FileOutcome::Skipped(SkipReason::Binary)
    ));
    assert_eq!(binary.size, 6);

    let file = prepare_file("src/lib.rs", "sha", b"fn one() {}\r\nfn two() {}\r\n");
    let FileOutcome::Indexed {
        language,
        content,
        line_count,
        chunks,
        ..
    } = file.outcome
    else {
        panic!("expected an indexed file");
    };
    assert_eq!(language, Some("rust"));
    assert!(!content.contains('\r'));
    assert_eq!(line_count, 2);
    assert!(!chunks.is_empty());
}

#[tokio::test]
async fn apply_twice_keeps_only_the_second_version() {
    let tmp = tempfile::tempdir().unwrap();
    let db = open_db(&tmp);
    let FileOutcome::Indexed {
        chunks: v2_chunks, ..
    } = prepare_file("src/handler.rs", "v2", V2.as_bytes()).outcome
    else {
        panic!("V2 is indexed");
    };
    let (stats, rows) = db
        .write(|conn| {
            let repo = insert_repo(conn, 1, "acme/api");
            apply_files(
                conn,
                repo,
                &[prepare_file("src/handler.rs", "v1", V1.as_bytes())],
            )?;
            assert_eq!(fts_hits(conn, "chunks_fts", "zebraquokka"), 1);
            let stats = apply_files(
                conn,
                repo,
                &[prepare_file("src/handler.rs", "v2", V2.as_bytes())],
            )?;
            let rows = (
                count(conn, "SELECT count(*) FROM files"),
                count(conn, "SELECT count(*) FROM chunks"),
                fts_hits(conn, "chunks_fts", "zebraquokka"),
                fts_hits(conn, "chunks_fts", "platypus"),
                fts_hits(conn, "symbols_fts", "\"quokka\""),
                count(
                    conn,
                    "SELECT count(*) FROM symbols WHERE name = 'zebra_quokka_handler'",
                ),
                count(
                    conn,
                    "SELECT count(*) FROM symbols WHERE name = 'platypus_handler'",
                ),
                existing_files(conn, repo)?,
            );
            Ok::<_, rusqlite::Error>((stats, rows))
        })
        .await
        .unwrap();
    let (files, chunks, old_hits, new_hits, old_symbol_hits, old_symbols, new_symbols, existing) =
        rows;
    assert_eq!(stats.indexed, 1);
    assert_eq!(files, 1);
    assert_eq!(chunks, v2_chunks.len() as i64);
    assert_eq!(old_hits, 0);
    assert!(new_hits >= 1);
    assert_eq!(old_symbol_hits, 0);
    assert_eq!(old_symbols, 0);
    assert_eq!(new_symbols, 1);
    assert_eq!(
        existing.get("src/handler.rs").map(String::as_str),
        Some("v2")
    );
}

#[tokio::test]
async fn skipped_files_are_recorded_without_content() {
    let tmp = tempfile::tempdir().unwrap();
    let db = open_db(&tmp);
    let (stats, reason, content_null, chunks) = db
        .write(|conn| {
            let repo = insert_repo(conn, 1, "acme/api");
            let stats = apply_files(
                conn,
                repo,
                &[
                    prepare_file("logo.png", "png", b"\x89PNG\0\0\0"),
                    skipped("big.rs", "big", 99, SkipReason::NotInArchive),
                ],
            )?;
            let (reason, content_null): (String, bool) = conn.query_row(
                "SELECT skip_reason, content IS NULL FROM files WHERE path = 'logo.png'",
                [],
                |row| Ok((row.get(0)?, row.get(1)?)),
            )?;
            Ok::<_, rusqlite::Error>((
                stats,
                reason,
                content_null,
                count(conn, "SELECT count(*) FROM chunks"),
            ))
        })
        .await
        .unwrap();
    assert_eq!(stats.skipped, 2);
    assert_eq!(stats.indexed, 0);
    assert_eq!(reason, "binary");
    assert!(content_null);
    assert_eq!(chunks, 0);
}

#[tokio::test]
async fn delete_paths_removes_every_row_of_the_file() {
    let tmp = tempfile::tempdir().unwrap();
    let db = open_db(&tmp);
    let after = db
        .write(|conn| {
            let repo = insert_repo(conn, 1, "acme/api");
            apply_files(
                conn,
                repo,
                &[
                    prepare_file("src/handler.rs", "v2", V2.as_bytes()),
                    prepare_file("src/other.rs", "o", V1.as_bytes()),
                ],
            )?;
            assert_eq!(fts_hits(conn, "chunks_fts", "platypus"), 1);
            assert!(fts_hits(conn, "symbols_fts", "\"latypus\"") >= 1);
            let deleted = delete_paths(conn, repo, &["src/handler.rs".to_string(), "missing.rs".to_string()])?;
            assert_eq!(deleted, 1);
            Ok::<_, rusqlite::Error>((
                count(conn, "SELECT count(*) FROM files WHERE path = 'src/handler.rs'"),
                count(conn, "SELECT count(*) FROM chunks c JOIN files f ON f.id = c.file_id WHERE f.path = 'src/other.rs'"),
                count(conn, "SELECT count(*) FROM chunks"),
                count(conn, "SELECT count(*) FROM symbols WHERE name LIKE 'platypus%'"),
                fts_hits(conn, "chunks_fts", "platypus"),
                fts_hits(conn, "symbols_fts", "\"latypus\""),
                fts_hits(conn, "chunks_fts", "zebraquokka"),
            ))
        })
        .await
        .unwrap();
    let (files, other_chunks, all_chunks, symbols, chunk_hits, symbol_hits, other_hits) = after;
    assert_eq!(files, 0);
    assert_eq!(all_chunks, other_chunks);
    assert_eq!(symbols, 0);
    assert_eq!(chunk_hits, 0);
    assert_eq!(symbol_hits, 0);
    assert_eq!(other_hits, 1);
}

#[tokio::test]
async fn purge_repository_removes_the_repository_and_its_rows() {
    let tmp = tempfile::tempdir().unwrap();
    let db = open_db(&tmp);
    let after = db
        .write(|conn| {
            let repo = insert_repo(conn, 1, "acme/api");
            let other = insert_repo(conn, 2, "acme/web");
            let files: Vec<_> = (0..250)
                .map(|i| prepare_file(&format!("src/f{i}.rs"), "s", V2.as_bytes()))
                .collect();
            apply_files(conn, repo, &files)?;
            apply_files(
                conn,
                other,
                &[prepare_file("src/keep.rs", "k", V1.as_bytes())],
            )?;
            while !purge_batch(conn, repo)? {}
            Ok::<_, rusqlite::Error>((
                count(conn, "SELECT count(*) FROM repositories"),
                count(conn, "SELECT count(*) FROM files"),
                count(
                    conn,
                    "SELECT count(*) FROM symbols WHERE repo_id <> (SELECT id FROM repositories)",
                ),
                fts_hits(conn, "chunks_fts", "platypus"),
                fts_hits(conn, "chunks_fts", "zebraquokka"),
            ))
        })
        .await
        .unwrap();
    assert_eq!(after, (1, 1, 0, 0, 1));
}

#[tokio::test]
async fn purge_batch_deletes_one_bounded_batch_per_writer_turn() {
    let tmp = tempfile::tempdir().unwrap();
    let db = open_db(&tmp);
    let repo = db
        .write(|conn| {
            let repo = insert_repo(conn, 1, "acme/api");
            let files: Vec<_> = (0..450)
                .map(|i| prepare_file(&format!("src/f{i}.rs"), "s", V2.as_bytes()))
                .collect();
            apply_files(conn, repo, &files)?;
            Ok::<_, rusqlite::Error>(repo)
        })
        .await
        .unwrap();

    let done = db.write(move |conn| purge_batch(conn, repo)).await.unwrap();
    assert!(!done, "450 files take more than one batch");
    let left = db
        .read(|conn| Ok::<_, rusqlite::Error>(count(conn, "SELECT count(*) FROM files")))
        .await
        .unwrap();
    assert_eq!(left, 250);

    // The writer is free between batches: another write commits before the purge goes on.
    db.write(|conn| {
        conn.execute(
            "INSERT INTO webhook_deliveries (delivery_id, event, received_at) VALUES ('d1', 'push', 1)",
            [],
        )
    })
    .await
    .unwrap();

    let mut calls = 1;
    while !db.write(move |conn| purge_batch(conn, repo)).await.unwrap() {
        calls += 1;
        assert!(calls < 10, "the purge must finish");
    }
    let after = db
        .read(|conn| {
            Ok::<_, rusqlite::Error>((
                count(conn, "SELECT count(*) FROM repositories"),
                count(conn, "SELECT count(*) FROM files"),
                count(conn, "SELECT count(*) FROM chunks"),
                count(conn, "SELECT count(*) FROM symbols"),
                fts_hits(conn, "chunks_fts", "platypus"),
                fts_hits(conn, "symbols_fts", "\"latypus\""),
                count(conn, "SELECT count(*) FROM webhook_deliveries"),
            ))
        })
        .await
        .unwrap();
    assert_eq!(after, (0, 0, 0, 0, 0, 0, 1));
}

#[tokio::test]
async fn file_row_deletes_use_indexes_and_rowid_lookups() {
    let tmp = tempfile::tempdir().unwrap();
    let db = open_db(&tmp);
    let plans: Vec<Vec<String>> = db
        .read(|conn| {
            DELETE_FILE_ROWS_SQL
                .iter()
                .map(|sql| {
                    conn.prepare(&format!("EXPLAIN QUERY PLAN {sql}"))?
                        .query_map([1], |row| row.get(3))?
                        .collect()
                })
                .collect::<rusqlite::Result<_>>()
        })
        .await
        .unwrap();
    for (sql, plan) in DELETE_FILE_ROWS_SQL.iter().zip(&plans) {
        for step in plan {
            // FTS5 takes `rowid IN (…)` one value at a time (idxStr `=`); plain tables use an index.
            let ok = step.starts_with("SEARCH ")
                || step.starts_with("LIST SUBQUERY")
                || step.ends_with("VIRTUAL TABLE INDEX 0:=");
            assert!(ok, "{sql}: {plan:?}");
        }
    }
}

#[tokio::test]
async fn delete_paths_in_slices_lets_other_writes_interleave() {
    let tmp = tempfile::tempdir().unwrap();
    let db = open_db(&tmp);
    let repo = db
        .write(|conn| {
            let repo = insert_repo(conn, 1, "acme/api");
            let files: Vec<_> = (0..450)
                .map(|i| prepare_file(&format!("src/f{i}.rs"), "s", V2.as_bytes()))
                .collect();
            apply_files(conn, repo, &files)?;
            Ok::<_, rusqlite::Error>(repo)
        })
        .await
        .unwrap();
    let paths: Vec<String> = (0..450).map(|i| format!("src/f{i}.rs")).collect();

    let mut deleted = 0;
    for (turn, slice) in paths.chunks(DELETE_BATCH_FILES).enumerate() {
        let slice = slice.to_vec();
        deleted += db
            .write(move |conn| delete_paths(conn, repo, &slice))
            .await
            .unwrap();
        db.write(move |conn| {
            conn.execute(
                "INSERT INTO webhook_deliveries (delivery_id, event, received_at) VALUES (?1, 'push', 1)",
                [format!("d{turn}")],
            )
        })
        .await
        .unwrap();
    }
    let after = db
        .read(|conn| {
            Ok::<_, rusqlite::Error>((
                count(conn, "SELECT count(*) FROM files"),
                count(conn, "SELECT count(*) FROM chunks"),
                count(conn, "SELECT count(*) FROM symbols"),
                fts_hits(conn, "chunks_fts", "platypus"),
                count(conn, "SELECT count(*) FROM webhook_deliveries"),
            ))
        })
        .await
        .unwrap();
    assert_eq!(deleted, 450);
    assert_eq!(after, (0, 0, 0, 0, 3));
}
